void LibBgfxBackend::apply_video_mode(const VideoMode& mode) {
  if (mode == applied_video_mode_) return;
#ifdef _WIN32
  if (hwnd_) {
    MONITORINFO monitor{};
    monitor.cbSize = sizeof(monitor);
    if (!GetMonitorInfoW(MonitorFromWindow(hwnd_, MONITOR_DEFAULTTONEAREST), &monitor))
      return;
    const RECT screen = monitor.rcMonitor;
    // A legacy fullscreen flag can accompany a small saved resolution. Keep
    // that mode resizable; a borderless window only makes sense at monitor size.
    // A framed window of exactly the monitor size cannot fit (title bar, frame
    // and taskbar push it off the screen, hiding the bottom of the picture),
    // so that size is borderless whatever the windowed flag says.
    const bool fullscreen = mode.width == screen.right - screen.left &&
        mode.height == screen.bottom - screen.top;
    const DWORD style = fullscreen ? WS_POPUP : WS_OVERLAPPEDWINDOW;
    const auto previous = GetWindowLongPtrW(hwnd_, GWL_STYLE);
    const bool style_changed = (previous & (WS_OVERLAPPEDWINDOW | WS_POPUP)) != style;
    RECT client{};
    GetClientRect(hwnd_, &client);
    if (style_changed || client.right != mode.width || client.bottom != mode.height) {
      if (IsZoomed(hwnd_)) ShowWindow(hwnd_, SW_RESTORE);
      SetWindowLongPtrW(hwnd_, GWL_STYLE,
          (previous & ~(WS_OVERLAPPEDWINDOW | WS_POPUP)) | style);
      RECT frame{0, 0, mode.width, mode.height};
      AdjustWindowRectEx(&frame, style, FALSE, GetWindowLongW(hwnd_, GWL_EXSTYLE));
      const RECT area = fullscreen ? screen : monitor.rcWork;
      const int w = frame.right - frame.left, h = frame.bottom - frame.top;
      const int x = area.left + std::max(0, int(area.right - area.left - w) / 2);
      const int y = area.top + std::max(0, int(area.bottom - area.top - h) / 2);
      SetWindowPos(hwnd_, nullptr, x, y, w, h,
                   SWP_NOZORDER | SWP_NOACTIVATE | SWP_FRAMECHANGED);
    }
  }
#endif
  applied_video_mode_ = mode;
}

  bool LibBgfxBackend::screen_size_keep(const float center[3], float radius, void* user) {
    return static_cast<const LibBgfxBackend*>(user)->screen_size_visible(center, radius);
  }

  bool LibBgfxBackend::screen_size_visible(const float center[3], float radius) const {
    const float dx = center[0] - cull_eye_[0];
    const float dy = center[1] - cull_eye_[1];
    const float dz = center[2] - cull_eye_[2];
    if (std::sqrt(dx * dx + dy * dy + dz * dz) - radius < 40.f) return true;
    if (width_ <= 0 || height_ <= 0) return true;
    const float rx = center[0];
    const float ry = center[1];
    const float rz = -center[2];
    const float ahead = cull_view_[2] * rx + cull_view_[6] * ry + cull_view_[10] * rz +
                        cull_view_[14];
    if (ahead < 0.5f) return true;
    const float box = std::max(radius * std::fabs(cull_proj_[0]) / ahead * static_cast<float>(width_),
                                radius * std::fabs(cull_proj_[5]) / ahead * static_cast<float>(height_));
    // Specks go. A building of a few metres still covers the screen at range.
    // Default 4 px (#252, was 2); the debug menu overrides it.
    return box >= std::clamp(render_debug().far_cull_px, 0.f, 64.f);
  }

  namespace {
  // bx::mtxProj writes near as the smaller depth. Swap that so 5 km still has
  // a usable step: near becomes 1, far becomes 0. The shadow orthographic
  // views keep the original matrix.
  void reverse_scene_projection(float* proj) {
    // homogeneousDepth is the [-1, 1] range. Direct3D is [0, 1], near at 0.
    if (bgfx::getCaps()->homogeneousDepth) {
      proj[2] = -proj[2];
      proj[6] = -proj[6];
      proj[10] = -proj[10];
      proj[14] = -proj[14];
    } else {
      proj[2] = proj[3] - proj[2];
      proj[6] = proj[7] - proj[6];
      proj[10] = proj[11] - proj[10];
      proj[14] = proj[15] - proj[14];
    }
  }
  }  // namespace

  void LibBgfxBackend::flush()
{
    ++frames_;
    if (!paint_texture_take_released().empty()) release_paint_textures(false);
    for (auto it=font_tex_.begin();it!=font_tex_.end();) {
      if (!slrr_font_asset_live(it->first)) {
        if (bgfx::isValid(it->second)) bgfx::destroy(it->second);
        it=font_tex_.erase(it);
      } else ++it;
    }
    if (!ready_) return;
    struct FrameCache {
      FrameCache() { scene_instances_frame_cache(true); }
      ~FrameCache() { scene_instances_frame_cache(false); }
    } frame_cache;
    view_draws_.fill(0);
    auto video = host_game_options().video;
    const auto& debug_render = debug_overlay_.render_options();
    // Advanced video options (#377): 3 km by default.
    video.view_distance = float(std::clamp(host_enhanced_graphics().view_distance, 500, 3000));
    apply_video_mode(video.mode);
    const bool loading = osd_loading_dialog() || !osd_loading_overlay().empty();
    const bool covered = !osd_loading_overlay().empty() && !video_fmv_block_osd();
    // A yielded section change must not expose its half-destroyed world.
    // Loading plates can present, as can a modal that blocks enter() after
    // loading finishes, such as the welcome dialog in a new career.
    if (scene_transition_blocks_presentation() && !loading && !osd_has_modal()) return;

    const auto old_width = width_, old_height = height_;
#ifdef _WIN32
    RECT rc{};
    if (hwnd_) {
      GetClientRect(hwnd_, &rc);
      if (rc.right > 0 && rc.bottom > 0) {
        width_ = rc.right;
        height_ = rc.bottom;
        osd_set_framebuffer(width_, height_);
      }
    }
#endif
    bgfx::SwapChain sc{};
    sc.nwh = hwnd_;
    sc.width = static_cast<uint32_t>(width_);
    sc.height = static_cast<uint32_t>(height_);
    const uint32_t msaa[] = {BGFX_RESET_NONE, BGFX_RESET_MSAA_X2,
                             BGFX_RESET_MSAA_X4, BGFX_RESET_MSAA_X8};
    // Debug overrides (#243) switch MSAA / anisotropy off without saving.
    const auto& overrides = render_debug();
    const uint32_t flags = (debug_render.vsync && host_enhanced_graphics().vsync ? BGFX_RESET_VSYNC : BGFX_RESET_NONE)
                           | (overrides.msaa ? msaa[std::clamp(host_enhanced_graphics().msaa, 0, 3)] : BGFX_RESET_NONE)
                           | (host_enhanced_graphics().anisotropic_filtering && overrides.anisotropic
                                  ? BGFX_RESET_MAXANISOTROPY : 0);
    if (width_ != old_width || height_ != old_height || flags != reset_flags_) {
      bgfx::reset(flags, &sc);
      reset_flags_ = flags;
    }
    float world_eye[3], world_at[3], world_up[3], world_fov = 60.f, world_zn = 0.05f,
                                     world_zf = 500.f;
    // Garage, dealer and car lot all use the script camera, which looks
    // at the car (or the empty bay). The free orbit is only a fallback.
    const auto* script_camera = fullscreen_script_camera();
    const auto* world_vp = script_camera ? gameref_get(script_camera->viewport) : nullptr;
    const bool world_inset = world_vp && (world_vp->vp_w < .99f || world_vp->vp_h < .99f);
    const bool world_cam = gameref_world_camera(world_eye, world_at, &world_fov,
                                                 &world_zn, &world_zf, world_up);

    float view[16];
    float proj[16];
    outdoor_lighting_ = world_cam && scene_instances_outdoor();
    if (world_cam) {
      const float render_eye[3] = {world_eye[0], world_eye[1], -world_eye[2]};
      refresh_distance_fog(render_eye);
    } else {
      fog_enabled_ = false;
    }
    if (world_cam) {
      if (outdoor_lighting_ || (script_camera && script_camera->follow_vehicle))
        world_zf = video.view_distance;
      const float aspect =
          height_ > 0 ? static_cast<float>(width_) / static_cast<float>(height_)
                      * (world_vp && world_vp->vp_h > 0.f ? world_vp->vp_w / world_vp->vp_h : 1.f)
                      : 1.333f;
      const bx::Vec3 eye{world_eye[0], world_eye[1], -world_eye[2]};
      const bx::Vec3 at{world_at[0], world_at[1], -world_at[2]};
      const bx::Vec3 up{world_up[0], world_up[1], -world_up[2]};
      bx::mtxLookAt(view, eye, at, up);
      bx::mtxProj(proj, world_fov, aspect, world_zn, world_zf,
                  bgfx::getCaps()->homogeneousDepth);
    } else {
      build_camera(view, proj);
    }

    video_fmv_pump();
    // prime.avi is the backdrop. Drawing it after the world hid the car.
    const bool fmv_bg = !covered && video_fmv_is_playing() && video_fmv_is_non_exclusive() &&
                        video_fmv_frame_ready();
    // Back to the menu closes that movie before the next one is ready.
    // A retired splash still counts as a widget but is not drawn, so the
    // frame was only the clear color. Keep the previous image instead.
    if (!covered) {
      perf::Scope scope(perf::Zone::Collect);
      sync_instances(view, proj);
    }
    auto is_opening = [](const std::string& path) {
      std::string low = path;
      for (char& c : low)
        c = static_cast<char>(std::tolower(static_cast<unsigned char>(c)));
      return low.find("opening") != std::string::npos;
    };
    bool show = video_fmv_frame_ready() || garage_ || loading;
    if (!show) {
      for (const OsdWidget& w : osd_widgets()) {
        if (w.hidden || w.dead || !w.background || w.icon_path.empty())
          continue;
        if (w.half_w > 0.9f && w.half_h > 0.9f &&
            (!is_opening(w.icon_path) || !opening_retired_)) {
          show = true;
          break;
        }
      }
    }
    if (!show) {
      for (const auto& i : instances_)
        if (i.sky) {
          show = true;
          break;
        }
    }
    if (!show && !world_cam && !instances_.empty()) show = true;
    if (!show && world_cam) {
      float fx = world_at[0] - world_eye[0];
      float fy = world_at[1] - world_eye[1];
      float fz = world_at[2] - world_eye[2];
      const float fl = std::sqrt(fx * fx + fy * fy + fz * fz);
      if (fl > 1e-4f) {
        fx /= fl;
        fy /= fl;
        fz /= fl;
      }
      for (const auto& i : instances_) {
        if (i.geometry->ground_polygons) {
          show = true;
          break;
        }
        const float x = i.transform[12] - world_eye[0];
        const float y = i.transform[13] - world_eye[1];
        const float z = -i.transform[14] - world_eye[2];
        const float ahead = fx * x + fy * y + fz * z;
        if (ahead > 0.05f && ahead < world_zf) {
          show = true;
          break;
        }
      }
    }
    if (!show)
      for (const auto& p : previews_)
        if (!p.instances.empty()) {
          show = true;
          break;
        }
    const bool show_debug = debug_overlay_.visible();
    if (shown_ && !show && !show_debug && !debug_was_visible_) return;
    // Offscreen shadow views run before either world view.
    float render_proj[16];
    std::memcpy(render_proj, proj, sizeof(render_proj));
    reverse_scene_projection(render_proj);
    const uint16_t world_view = fmv_bg ? kFmvLayer : kWorldView;
    const auto ww = static_cast<uint16_t>(width_);
    const auto hh = static_cast<uint16_t>(height_);
    bgfx::setViewFrameBuffer(kWorldView, BGFX_INVALID_HANDLE);
    bgfx::setViewFrameBuffer(kFmvLayer, BGFX_INVALID_HANDLE);
    if (fmv_bg) {
      bgfx::setViewRect(kWorldView, 0, 0, ww, hh);
      bgfx::setViewClear(kWorldView, BGFX_CLEAR_COLOR | BGFX_CLEAR_DEPTH | BGFX_CLEAR_STENCIL,
                         0x000000ff, 0.f, 0);
      set_view_sequential(kWorldView);
      draw_fmv(kWorldView);
      bgfx::setViewRect(world_view, 0, 0, ww, hh);
      bgfx::setViewClear(world_view, BGFX_CLEAR_DEPTH | BGFX_CLEAR_STENCIL, 0,
                         0.f, 0);
    } else {
      bgfx::setViewRect(world_view, 0, 0, ww, hh);
    }
    // The world view's clear colour and rect, reused by kWorldOpaqueView (#359).
    const uint32_t world_clear = (garage_ || world_cam) ? 0x3a342cff : 0x1a2230ff;
    std::array<uint16_t, 4> world_rect{0, 0, ww, hh};
    if (!fmv_bg)
      bgfx::setViewClear(world_view, BGFX_CLEAR_COLOR | BGFX_CLEAR_DEPTH | BGFX_CLEAR_STENCIL,
                         world_clear, 0.f, 0);
    if (world_cam && world_inset) {
      const int x = std::clamp(int(world_vp->vp_x * width_), 0, width_ - 1);
      const int y = std::clamp(int(world_vp->vp_y * height_), 0, height_ - 1);
      world_rect = {uint16_t(x), uint16_t(y),
                    uint16_t(std::clamp(int(world_vp->vp_w * width_), 1, width_ - x)),
                    uint16_t(std::clamp(int(world_vp->vp_h * height_), 1, height_ - y))};
      bgfx::setViewRect(world_view, world_rect[0], world_rect[1], world_rect[2], world_rect[3]);
    }
    bgfx::setViewTransform(world_view, view, render_proj);
    set_view_sequential(world_view);
    enc()->touch(world_view);

    // Menu/Splash: no garage SCX — stock MainMenu uses FMV or Dummy scene.
    if (!covered) {
      // Worker encoders (#270): the AO prepass, car lamp tiles and reflection
      // faces queue their draws and run beside the world submission.
      resolved_textures_.clear();
      defer_submits_ = parallel_submission_ready();
      update_local_light();
      update_static_shadow(world_cam ? world_eye : nullptr, video);
      {
        perf::Scope fixture_scope(perf::Zone::FixtureShadows);
        update_fixture_shadows(video);
      }
      const auto* car = script_camera && script_camera->follow_vehicle
          ? gameref_find_live(script_camera->follow_vehicle) : nullptr;
      float car_matrix[16];
      const auto* position = car && scene_instances_render_matrix(car->key, car_matrix)
          ? car_matrix + 12 : world_cam ? world_eye : nullptr;
      // Street lamp shadows are chosen around the followed car (#237), so
      // turning the camera does not move its shadows. Without a following
      // script camera (free or scripted views) the controlled car is used.
      {
        const auto* player = car ? car : gameref_find_live(part_controlled_vehicle());
        float player_matrix[16];
        if (player && scene_instances_render_matrix(player->key, player_matrix))
          set_lamp_shadow_focus(player_matrix + 12);
        else
          set_lamp_shadow_focus(nullptr);
        set_headlight_focus(player ? player->key : nullptr);
      }
      update_lamp_shadows(video);
      update_headlight_shadows(video);
      update_interior_sun(video);
      if(world_cam && !world_inset) {
        perf::Scope ao_scope(perf::Zone::AmbientOcclusion);
        update_ambient_occlusion(view,proj,ww,hh,world_view);
      }
      else destroy_ao_targets();
      update_car_depth(garage_ ? nullptr : position, video);
      update_smoke_shadow(video);
      // Every world camera reflects its scene. The car dealers have a map and a
      // script camera but neither the garage flag nor a followed car, so their
      // cars used to lose the cubemap and render matte.
      reflection_scene_ = garage_ || world_cam || (script_camera && script_camera->follow_vehicle);
      float reflection_position[3];
      const float* capture_position = position;
      // Script-space centre of a vehicle part, lowered by the height that
      // update_reflections adds back to the probe.
      const auto part_centre = [](const SceneInstance& part, float* out) {
        const auto& geometry = *part.geometry;
        const auto& m = part.transform;
        const float x = (geometry.info.bbox_min[0] + geometry.info.bbox_max[0]) * .5f * geometry.position_scale;
        const float y = (geometry.info.bbox_min[1] + geometry.info.bbox_max[1]) * .5f * geometry.position_scale;
        const float z = -(geometry.info.bbox_min[2] + geometry.info.bbox_max[2]) * .5f * geometry.position_scale;
        out[0] = m[0]*x + m[4]*y + m[8]*z + m[12];
        out[1] = m[1]*x + m[5]*y + m[9]*z + m[13] - .8f;
        out[2] = -(m[2]*x + m[6]*y + m[10]*z + m[14]);
      };
      if (garage_) {
        const auto body = std::find_if(instances_.begin(), instances_.end(),
            [](const SceneInstance& object) { return object.vehicle_material; });
        if (body != instances_.end()) {
          part_centre(*body, reflection_position);
          capture_position = reflection_position;
        }
      } else if (!car && world_cam) {
        // A showroom camera orbits the car on display. Capture from that car,
        // not from the camera, so its panels reflect the room around it.
        float best = 8.f * 8.f;
        for (const auto& object : instances_) {
          if (!object.vehicle_material) continue;
          float centre[3];
          part_centre(object, centre);
          const float dx = centre[0] - world_at[0];
          const float dy = centre[1] + .8f - world_at[1];
          const float dz = centre[2] - world_at[2];
          const float distance = dx * dx + dy * dy + dz * dz;
          if (distance < best) {
            best = distance;
            std::copy(centre, centre + 3, reflection_position);
            capture_position = reflection_position;
          }
        }
      }
      update_reflections(capture_position);
      // Every light is final: upload the light data texture before any
      // encoder binds it (#270).
      upload_light_data();
      defer_submits_ = false;
      const bool sky = world_cam && (outdoor_lighting_ ||
          std::any_of(instances_.begin(), instances_.end(),
                      [](const SceneInstance& instance) { return instance.sky; }));
      submit_world(world_view, BGFX_INVALID_HANDLE, world_rect,
                   BGFX_CLEAR_COLOR | BGFX_CLEAR_DEPTH | BGFX_CLEAR_STENCIL, world_clear,
                   view, render_proj, sky, [&] {
                     if (garage_ && !parts_.empty()) draw_scene(world_view);
                   });

      if (debug_render.sun_flare && video.flares) draw_sun_flare(view, render_proj, world_view);
      // Runtime reports only active-world nitrous children. Never submit this
      // optical glow to previews/reflection/shadow passes or the light arrays.
      if (video.flares) draw_nitro_flares(view, render_proj, world_view);
      // Tyre marks after the world's opaque and blended draws.
      if (world_cam) {
        draw_skid_marks(world_view);
        // Smoke last: it blends over the world, the cars and the marks.
        draw_particles(view, render_proj, world_view);
      }
    }
    // Previews start at view 8. OSD plates under the cars are view 7; the
    // rest of the interface is view 70.
    if (!covered && !fmv_bg) draw_fmv(kFmvLayer);
    // Boot intros own the frame. Menu OSD from the probe must not cover them.
    if ((garage_ || osd_overlay_ || loading) &&
        (debug_render.game_osd || loading || osd_has_modal()) &&
        !video_fmv_block_osd())
      draw_osd();
    if (!covered && !video_fmv_block_osd()) draw_previews();

    if (show_debug) {
      perf::Scope scope(perf::Zone::Osd);
      std::vector<Object*> vehicles;
      std::unordered_set<Object*> seen;
      const auto add = [&](Object* vehicle) {
        if (vehicle && seen.insert(vehicle).second) vehicles.push_back(vehicle);
      };
      const auto collect = [&](const auto& instances) {
        for (const auto& instance : instances)
          if (instance.vehicle_material)
            add(part_debug_chassis(part_render_owner(instance.key)));
      };
      collect(instances_);
      for (const auto& preview : previews_) collect(preview.instances);
      add(part_controlled_chassis());
      const char* capture = !host_enhanced_graphics().dynamic_reflections ? "disabled"
          : !reflection_scene_ ? "no world camera"
          : reflection_ready_ ? "live cubemap"
          : bgfx::isValid(reflection_cubes_[0]) ? "capturing" : "waiting for render target";
      publish_debug_stats();
      debug_overlay_.draw(hwnd_, ww, hh, capture, vehicles);
    }
    debug_was_visible_ = show_debug;
    {
      // Per-view GPU times need the bgfx profiler: on while the debug menu
      // is open, and for the per-pass --perf-log columns (#362).
      static bool profiler = false;
      if (profiler != (show_debug || perf::enabled())) {
        profiler = show_debug || perf::enabled();
        bgfx::setDebug(profiler ? BGFX_DEBUG_PROFILER : BGFX_DEBUG_NONE);
      }
    }
    auto& input = host_input();
    const bool capture = !lmb_down_ && !input.rmb_down && debug_overlay_.captures_mouse();
    if (capture && !input.debug_mouse_capture) {
      input.pointer_valid = false;
      osd_set_hover_at(-100.f, -100.f);
    }
    input.debug_mouse_capture = capture;
    {
      perf::Scope scope(perf::Zone::Present);
      bgfx::frame();
    }
    if (perf::enabled()) {
      // bgfx reports the frame its render thread finished last.
      const auto* stats = bgfx::getStats();
      const auto ms = [](int64_t ticks, int64_t frequency) {
        return frequency > 0 ? static_cast<double>(ticks) * 1000. / static_cast<double>(frequency) : 0.;
      };
      perf::RenderSample sample;
      sample.render_thread_ms = ms(stats->cpuTimeEnd - stats->cpuTimeBegin, stats->cpuTimerFreq);
      sample.gpu_ms = ms(stats->gpuTimeEnd - stats->gpuTimeBegin, stats->gpuTimerFreq);
      sample.wait_render_ms = ms(stats->waitRender, stats->cpuTimerFreq);
      sample.draws = stats->numDraw;
      for (const auto& instance : instances_) sample.instances += instance.sky ? 0u : 1u;
      for (const auto& batch : prop_batches_)
        sample.batch_instances += static_cast<uint32_t>(batch.instances.size());
      // Per-view GPU times exist while the bgfx profiler is on (#362).
      for (uint16_t i = 0; i < stats->numViews; ++i) {
        const auto& view = stats->viewStats[i];
        sample.gpu_pass_ms[size_t(render_gpu_pass(view.view))] +=
            ms(view.gpuTimeEnd - view.gpuTimeBegin, stats->gpuTimerFreq);
      }
      perf::set_render_sample(sample);
    }
    // The swap chain is filled while the window is hidden. Showing it first
    // presented one clear (0x1a2230) before the movie or the splash plate.
    const bool reveal = video_fmv_frame_ready() || garage_ || osd_overlay_ || show_debug;
    if (!shown_ && reveal && hwnd_) {
      ShowWindow(hwnd_, SW_SHOW);
      shown_ = true;
    }
  }

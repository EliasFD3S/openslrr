  bool LibBgfxBackend::open(int32_t width, int32_t height, const char* title)
{
    applied_video_mode_ = {};
    reset_flags_ = BGFX_RESET_VSYNC;
    width_ = width > 0 ? width : 800;
    height_ = height > 0 ? height : 600;

#ifdef _WIN32
    WNDCLASSEXA wc{};
    wc.cbSize = sizeof(wc);
    wc.style = CS_OWNDC;
    wc.lpfnWndProc = &LibBgfxBackend::wnd_proc;
    wc.hInstance = GetModuleHandleA(nullptr);
    wc.hIcon = LoadIconA(wc.hInstance, "IDI_APP");
    if (!wc.hIcon) wc.hIcon = LoadIconA(wc.hInstance, MAKEINTRESOURCEA(1));
    wc.hIconSm = wc.hIcon;
    wc.hCursor = reinterpret_cast<HCURSOR>(host_cursor_current());
    wc.lpszClassName = "slrr_host_libbgfx";
    RegisterClassExA(&wc);

    // width_/height_ are the client (Frontend.setFonts band). CreateWindow
    // takes the outer size; without the frame, the client falls under 800×600
    // and the first resize drops mediumFont from SLII17 to SLII11.
    RECT frame{0, 0, width_, height_};
    AdjustWindowRectEx(&frame, WS_OVERLAPPEDWINDOW, FALSE, 0);
    hwnd_ = CreateWindowExA(
        0, wc.lpszClassName, title ? title : "SLRR host",
        WS_OVERLAPPEDWINDOW, CW_USEDEFAULT, CW_USEDEFAULT,
        frame.right - frame.left, frame.bottom - frame.top, nullptr, nullptr,
        wc.hInstance, this);
    if (!hwnd_) {
      std::fprintf(stderr, "[bgfx] CreateWindow failed\n");
      return false;
    }
    const RAWINPUTDEVICE mouse{0x01, 0x02, 0, hwnd_};
    raw_mouse_ = RegisterRawInputDevices(&mouse, 1, sizeof(mouse)) != FALSE;
    if (wc.hIcon) {
      SendMessageA(hwnd_, WM_SETICON, ICON_BIG,
                   reinterpret_cast<LPARAM>(wc.hIcon));
      SendMessageA(hwnd_, WM_SETICON, ICON_SMALL,
                   reinterpret_cast<LPARAM>(wc.hIcon));
    }

    bgfx::Init init;
    init.type = bgfx::RendererType::Count;
    init.platformData.type = bgfx::NativeWindowHandleType::Default;
    init.swapChain.nwh = hwnd_;
    init.swapChain.width = static_cast<uint32_t>(width_);
    init.swapChain.height = static_cast<uint32_t>(height_);
    init.reset = BGFX_RESET_VSYNC;
    if (!bgfx::init(init)) {
      std::fprintf(stderr, "[bgfx] bgfx::init failed\n");
      return false;
    }
#else
    (void)title;
    bgfx::Init init;
    init.type = bgfx::RendererType::Noop;
    if (!bgfx::init(init)) return false;
#endif

    const bgfx::RendererType::Enum rt = bgfx::getRendererType();
    bgfx::ShaderHandle vsh = bgfx::createEmbeddedShader(k_vs, rt, "vs_mesh");
    bgfx::ShaderHandle fsh = bgfx::createEmbeddedShader(k_fs, rt, "fs_mesh");
    if (!bgfx::isValid(vsh) || !bgfx::isValid(fsh)) {
      std::fprintf(stderr, "[bgfx] embedded shaders missing for renderer %d\n",
                   static_cast<int>(rt));
      bgfx::shutdown();
      return false;
    }
    program_ = bgfx::createProgram(vsh, fsh, true);
    bgfx::ShaderHandle skin_vs = bgfx::createEmbeddedShader(k_skin, rt, "vs_skin");
    bgfx::ShaderHandle skin_fs = bgfx::createEmbeddedShader(k_fs, rt, "fs_mesh");
    if (bgfx::isValid(skin_vs) && bgfx::isValid(skin_fs))
      skin_program_ = bgfx::createProgram(skin_vs, skin_fs, true);
    else {
      if (bgfx::isValid(skin_vs)) bgfx::destroy(skin_vs);
      if (bgfx::isValid(skin_fs)) bgfx::destroy(skin_fs);
    }
    u_skin_bones_ = bgfx::createUniform("u_skinBones", bgfx::UniformType::Mat4, 48);
    static_shadow_program_ = bgfx::createProgram(
        bgfx::createEmbeddedShader(k_vs, rt, "vs_mesh"),
        bgfx::createEmbeddedShader(k_fs, rt, "fs_static_shadow"), true);
    inst_program_ = bgfx::createProgram(
        bgfx::createEmbeddedShader(k_vs, rt, "vs_mesh_inst"),
        bgfx::createEmbeddedShader(k_fs, rt, "fs_mesh"), true);
    inst_shadow_program_ = bgfx::createProgram(
        bgfx::createEmbeddedShader(k_vs, rt, "vs_mesh_inst"),
        bgfx::createEmbeddedShader(k_fs, rt, "fs_static_shadow"), true);
    present_program_ = bgfx::createProgram(
        bgfx::createEmbeddedShader(k_vs, rt, "vs_mesh"),
        bgfx::createEmbeddedShader(k_fs, rt, "fs_present"), true);
    hiz_program_ = bgfx::createProgram(
        bgfx::createEmbeddedShader(k_vs, rt, "vs_mesh"),
        bgfx::createEmbeddedShader(k_fs, rt, "fs_hiz"), true);
    u_hiz_params_ = bgfx::createUniform("u_hizParams", bgfx::UniformType::Vec4);
    s_static_shadow_ = bgfx::createUniform("s_staticShadow", bgfx::UniformType::Sampler);
    u_static_shadow_mtx_ = bgfx::createUniform("u_staticShadowMtx", bgfx::UniformType::Mat4);
    u_static_shadow_params_ = bgfx::createUniform("u_staticShadowParams", bgfx::UniformType::Vec4);
    u_static_shadow_eye_ = bgfx::createUniform("u_staticShadowEye", bgfx::UniformType::Vec4);
    vehicle_program_ = bgfx::createProgram(
        bgfx::createEmbeddedShader(k_vehicle, rt, "vs_vehicle"),
        bgfx::createEmbeddedShader(k_vehicle, rt, "fs_vehicle"), true);
    s_mix_ = bgfx::createUniform("s_vehicleMix", bgfx::UniformType::Sampler);
    s_env_ = bgfx::createUniform("s_vehicleEnv", bgfx::UniformType::Sampler);
    s_bake_ = bgfx::createUniform("s_vehicleBake", bgfx::UniformType::Sampler);
    u_layers_ = bgfx::createUniform("u_vehicleLayers", bgfx::UniformType::Vec4);
    u_channels_ = bgfx::createUniform("u_vehicleChannels", bgfx::UniformType::Vec4);
    u_base_uv_ = bgfx::createUniform("u_vehicleBaseUv", bgfx::UniformType::Vec4);
    u_mix_uv_ = bgfx::createUniform("u_vehicleMixUv", bgfx::UniformType::Vec4);
    u_env_uv_ = bgfx::createUniform("u_vehicleEnvUv", bgfx::UniformType::Vec4);
    u_diffuse_ = bgfx::createUniform("u_vehicleDiffuse", bgfx::UniformType::Vec4);
    u_spec_ = bgfx::createUniform("u_vehicleSpec", bgfx::UniformType::Vec4);
    u_sun_diff_ = bgfx::createUniform("u_sunDiff", bgfx::UniformType::Vec4);
    u_sun_amb_ = bgfx::createUniform("u_sunAmb", bgfx::UniformType::Vec4);
    u_sun_spec_ = bgfx::createUniform("u_sunSpec", bgfx::UniformType::Vec4);
    s_reflection_cube_ = bgfx::createUniform("s_sceneReflection", bgfx::UniformType::Sampler);
    u_reflection_probe_ = bgfx::createUniform("u_reflectionProbe", bgfx::UniformType::Vec4);
    u_reflection_box_min_ = bgfx::createUniform("u_reflectionBoxMin", bgfx::UniformType::Vec4);
    u_reflection_box_max_ = bgfx::createUniform("u_reflectionBoxMax", bgfx::UniformType::Vec4);
    u_dynamic_reflection_ = bgfx::createUniform("u_dynamicReflection", bgfx::UniformType::Vec4);
    u_local_light_ = bgfx::createUniform("u_localLight", bgfx::UniformType::Vec4);
    s_car_depth_ = bgfx::createUniform("s_carDepth", bgfx::UniformType::Sampler);
    u_car_depth_mtx_ = bgfx::createUniform("u_carDepthMtx", bgfx::UniformType::Mat4);
    u_car_depth_params_ = bgfx::createUniform("u_carDepthParams", bgfx::UniformType::Vec4);
    u_cloud_wind_ = bgfx::createUniform("u_cloudWind", bgfx::UniformType::Vec4);
    u_cloud_sky_ = bgfx::createUniform("u_cloudSky", bgfx::UniformType::Vec4);
    u_fog_color_ = bgfx::createUniform("u_fogColor", bgfx::UniformType::Vec4);
    u_fog_range_ = bgfx::createUniform("u_fogRange", bgfx::UniformType::Vec4);
    u_fog_eye_ = bgfx::createUniform("u_fogEye", bgfx::UniformType::Vec4);
    u_sun_dir_ = bgfx::createUniform("u_sunDir", bgfx::UniformType::Vec4);
    bgfx::ShaderHandle white_vs =
        bgfx::createEmbeddedShader(k_shadow_white, rt, "vs_shadow_cast");
    bgfx::ShaderHandle white_fs =
        bgfx::createEmbeddedShader(k_shadow_white, rt, "fs_white");
    if (bgfx::isValid(white_vs) && bgfx::isValid(white_fs))
      shadow_program_ = bgfx::createProgram(white_vs, white_fs, true);
    else {
      if (bgfx::isValid(white_vs)) bgfx::destroy(white_vs);
      if (bgfx::isValid(white_fs)) bgfx::destroy(white_fs);
    }
    bgfx::ShaderHandle recv_vs =
        bgfx::createEmbeddedShader(k_shadow_recv, rt, "vs_shadow_recv");
    bgfx::ShaderHandle recv_fs =
        bgfx::createEmbeddedShader(k_shadow_recv, rt, "fs_shadow_recv");
    if (bgfx::isValid(recv_vs) && bgfx::isValid(recv_fs))
      shadow_recv_ = bgfx::createProgram(recv_vs, recv_fs, true);
    else {
      if (bgfx::isValid(recv_vs)) bgfx::destroy(recv_vs);
      if (bgfx::isValid(recv_fs)) bgfx::destroy(recv_fs);
    }
    u_shadow_mtx_ = bgfx::createUniform("u_shadowMtx", bgfx::UniformType::Mat4);
    if (!bgfx::isValid(shadow_program_) || !bgfx::isValid(shadow_recv_))
      std::fprintf(stderr, "[shadow] shader program creation failed: caster=%d receiver=%d\n",
                   bgfx::isValid(shadow_program_), bgfx::isValid(shadow_recv_));
    u_shadow_ramp_ = bgfx::createUniform("u_shadowRamp", bgfx::UniformType::Vec4);
    // bgfx returns an invalid program, without a message in Release, when the
    // fragment $input list differs from the vertex $output list. The features
    // behind these programs then switch themselves off silently.
    const std::pair<const char*, bgfx::ProgramHandle> programs[] = {
        {"mesh", program_}, {"skin", skin_program_},
        {"static_shadow", static_shadow_program_}, {"inst", inst_program_},
        {"inst_shadow", inst_shadow_program_}, {"present", present_program_},
        {"hiz", hiz_program_}, {"vehicle", vehicle_program_}};
    for (const auto& [name, handle] : programs)
      if (!bgfx::isValid(handle))
        std::fprintf(stderr, "[bgfx] program %s failed to link\n", name);
    layout_.begin()
        .add(bgfx::Attrib::Position, 3, bgfx::AttribType::Float)
        .add(bgfx::Attrib::Normal, 3, bgfx::AttribType::Float)
        .add(bgfx::Attrib::TexCoord0, 2, bgfx::AttribType::Float)
        .add(bgfx::Attrib::TexCoord1, 2, bgfx::AttribType::Float)
        .add(bgfx::Attrib::TexCoord2, 2, bgfx::AttribType::Float)
        .add(bgfx::Attrib::Color0, 4, bgfx::AttribType::Uint8, true)
        .end();

    // 1x1 white fallback texture.
    const uint32_t white = 0xffffffff;
    white_tex_ = bgfx::createTexture2D(1, 1, false, 1, bgfx::TextureFormat::RGBA8,
                                       0, bgfx::copy(&white, sizeof(white)));
    depth_white_ = bgfx::createTexture2D(1, 1, false, 1, bgfx::TextureFormat::D32F,
        BGFX_TEXTURE_RT | BGFX_SAMPLER_U_CLAMP | BGFX_SAMPLER_V_CLAMP |
        BGFX_SAMPLER_COMPARE_LEQUAL);
    s_tex_ = bgfx::createUniform("s_texColor", bgfx::UniformType::Sampler);
    s_lightmap_ = bgfx::createUniform("s_lightmap", bgfx::UniformType::Sampler);
    s_mesh_mix_ = bgfx::createUniform("s_meshMix", bgfx::UniformType::Sampler);
    u_alpha_test_ = bgfx::createUniform("u_alphaTest", bgfx::UniformType::Vec4);
    u_color_ = bgfx::createUniform("u_color", bgfx::UniformType::Vec4);
    u_lightmap_ = bgfx::createUniform("u_lightmap", bgfx::UniformType::Vec4);
    u_lightmap_uv_ = bgfx::createUniform("u_lightmapUv", bgfx::UniformType::Vec4);
    u_mesh_base_uv_ = bgfx::createUniform("u_meshBaseUv", bgfx::UniformType::Vec4);
    u_mesh_mix_uv_ = bgfx::createUniform("u_meshMixUv", bgfx::UniformType::Vec4);
    const float white_c[4] = {1.f, 1.f, 1.f, 1.f};
    bgfx::setUniform(u_color_, white_c);

    bgfx::setViewClear(kWorldView, BGFX_CLEAR_COLOR | BGFX_CLEAR_DEPTH | BGFX_CLEAR_STENCIL,
                       0x1c1814ff, 0.f, 0);
    ready_ = true;
    quit_ = false;
    video_fmv_set_hwnd(hwnd_);
    std::printf("[bgfx] open %dx%d GPU=libbgfx renderer=%s\n", width_, height_,
                bgfx::getRendererName(rt));
    return true;
  }
  void LibBgfxBackend::close()
{
    debug_overlay_.shutdown();
    debug_was_visible_ = false;
    host_input().debug_mouse_capture = false;
    clear_scene();
    for (auto& kv : osd_tex_) {
      if (bgfx::isValid(kv.second) &&
          (!bgfx::isValid(white_tex_) || kv.second.idx != white_tex_.idx))
        bgfx::destroy(kv.second);
    }
    osd_tex_.clear();
    gps_hud_path_.clear();
    hud_preview_meshes_.clear();
    for (auto& kv : font_tex_) {
      if (bgfx::isValid(kv.second)) bgfx::destroy(kv.second);
    }
    font_tex_.clear();
    if (bgfx::isValid(white_tex_)) {
      bgfx::destroy(white_tex_);
      white_tex_ = BGFX_INVALID_HANDLE;
    }
    if (bgfx::isValid(depth_white_)) {
      bgfx::destroy(depth_white_);
      depth_white_ = BGFX_INVALID_HANDLE;
    }
    if (bgfx::isValid(s_tex_)) {
      bgfx::destroy(s_tex_);
      s_tex_ = BGFX_INVALID_HANDLE;
    }
    if (bgfx::isValid(s_lightmap_)) {
      bgfx::destroy(s_lightmap_);
      s_lightmap_ = BGFX_INVALID_HANDLE;
    }
    if (bgfx::isValid(s_mesh_mix_)) {
      bgfx::destroy(s_mesh_mix_);
      s_mesh_mix_ = BGFX_INVALID_HANDLE;
    }
    if (bgfx::isValid(u_lightmap_)) {
      bgfx::destroy(u_lightmap_);
      u_lightmap_ = BGFX_INVALID_HANDLE;
    }
    if (bgfx::isValid(u_lightmap_uv_)) {
      bgfx::destroy(u_lightmap_uv_);
      u_lightmap_uv_ = BGFX_INVALID_HANDLE;
    }
    if (bgfx::isValid(u_mesh_base_uv_)) {
      bgfx::destroy(u_mesh_base_uv_);
      u_mesh_base_uv_ = BGFX_INVALID_HANDLE;
    }
    if (bgfx::isValid(u_mesh_mix_uv_)) {
      bgfx::destroy(u_mesh_mix_uv_);
      u_mesh_mix_uv_ = BGFX_INVALID_HANDLE;
    }
    if (bgfx::isValid(u_alpha_test_)) {
      bgfx::destroy(u_alpha_test_);
      u_alpha_test_ = BGFX_INVALID_HANDLE;
    }
    if (bgfx::isValid(u_color_)) {
      bgfx::destroy(u_color_);
      u_color_ = BGFX_INVALID_HANDLE;
    }
    destroy_scene_target();
    destroy_hiz();
    if (bgfx::isValid(present_program_)) bgfx::destroy(present_program_);
    present_program_ = BGFX_INVALID_HANDLE;
    if (bgfx::isValid(hiz_program_)) bgfx::destroy(hiz_program_);
    hiz_program_ = BGFX_INVALID_HANDLE;
    if (bgfx::isValid(u_hiz_params_)) bgfx::destroy(u_hiz_params_);
    u_hiz_params_ = BGFX_INVALID_HANDLE;
    if (bgfx::isValid(program_)) {
      bgfx::destroy(program_);
      program_ = BGFX_INVALID_HANDLE;
    }
    if (bgfx::isValid(inst_program_)) {
      bgfx::destroy(inst_program_);
      inst_program_ = BGFX_INVALID_HANDLE;
    }
    if (bgfx::isValid(inst_shadow_program_)) {
      bgfx::destroy(inst_shadow_program_);
      inst_shadow_program_ = BGFX_INVALID_HANDLE;
    }
    if (bgfx::isValid(skin_program_)) {
      bgfx::destroy(skin_program_);
      skin_program_ = BGFX_INVALID_HANDLE;
    }
    if (bgfx::isValid(u_skin_bones_)) {
      bgfx::destroy(u_skin_bones_);
      u_skin_bones_ = BGFX_INVALID_HANDLE;
    }
    if (bgfx::isValid(vehicle_program_)) bgfx::destroy(vehicle_program_);
    vehicle_program_ = BGFX_INVALID_HANDLE;
    if (bgfx::isValid(shadow_program_)) bgfx::destroy(shadow_program_);
    shadow_program_ = BGFX_INVALID_HANDLE;
    if (bgfx::isValid(shadow_recv_)) bgfx::destroy(shadow_recv_);
    shadow_recv_ = BGFX_INVALID_HANDLE;
    if (bgfx::isValid(u_shadow_mtx_)) bgfx::destroy(u_shadow_mtx_);
    u_shadow_mtx_ = BGFX_INVALID_HANDLE;
    if (bgfx::isValid(u_shadow_ramp_)) bgfx::destroy(u_shadow_ramp_);
    u_shadow_ramp_ = BGFX_INVALID_HANDLE;
    destroy_reflections();
    if (bgfx::isValid(car_depth_fb_)) bgfx::destroy(car_depth_fb_);
    car_depth_fb_ = BGFX_INVALID_HANDLE;
    car_depth_tex_ = BGFX_INVALID_HANDLE;
    car_depth_active_ = false;
    if (bgfx::isValid(static_shadow_program_)) bgfx::destroy(static_shadow_program_);
    if (bgfx::isValid(static_shadow_fb_)) bgfx::destroy(static_shadow_fb_);
    static_shadow_program_ = BGFX_INVALID_HANDLE;
    static_shadow_fb_ = BGFX_INVALID_HANDLE;
    static_shadow_tex_ = BGFX_INVALID_HANDLE;
    static_shadow_world_ = nullptr;
    static_shadow_active_ = false;
    for (auto* handle : {&s_static_shadow_, &u_static_shadow_mtx_, &u_static_shadow_params_, &u_static_shadow_eye_}) {
      if (bgfx::isValid(*handle)) bgfx::destroy(*handle);
      *handle = BGFX_INVALID_HANDLE;
    }
    for (int i = 0; i < kShadowSlots; ++i) {
      if (bgfx::isValid(shadow_fb_[i])) bgfx::destroy(shadow_fb_[i]);
      shadow_fb_[i] = BGFX_INVALID_HANDLE;
      shadow_tex_[i] = BGFX_INVALID_HANDLE;
    }
    for (auto* handle : {&s_mix_, &s_env_, &s_bake_, &u_layers_, &u_channels_, &u_base_uv_, &u_mix_uv_, &u_env_uv_, &u_diffuse_, &u_spec_, &u_sun_diff_, &u_sun_amb_, &u_sun_spec_, &u_sun_dir_, &u_cloud_sky_, &u_cloud_wind_, &u_fog_color_, &u_fog_range_, &u_fog_eye_, &s_reflection_cube_, &u_dynamic_reflection_, &u_reflection_probe_, &u_reflection_box_min_, &u_reflection_box_max_, &u_local_light_, &s_car_depth_, &u_car_depth_mtx_, &u_car_depth_params_}) {
      if(bgfx::isValid(*handle)) bgfx::destroy(*handle);
      *handle = BGFX_INVALID_HANDLE;
    }
    if (ready_) bgfx::shutdown();
#ifdef _WIN32
    if (hwnd_) {
      DestroyWindow(hwnd_);
      hwnd_ = nullptr;
    }
#endif
    ready_ = false;
  }
  void LibBgfxBackend::pump(int32_t /*ms*/)
{
#ifdef _WIN32
    MSG msg;
    while (PeekMessageA(&msg, nullptr, 0, 0, PM_REMOVE)) {
      if (msg.message == WM_QUIT) {
        quit_ = true;
        break;
      }
      TranslateMessage(&msg);
      DispatchMessageA(&msg);
    }
    host_input_poll_keys();
#endif
  }
void LibBgfxBackend::apply_video_mode(const VideoMode& mode) {
  if (mode == applied_video_mode_) return;
#ifdef _WIN32
  if (hwnd_) {
    MONITORINFO monitor{};
    monitor.cbSize = sizeof(monitor);
    if (!GetMonitorInfoW(MonitorFromWindow(hwnd_, MONITOR_DEFAULTTONEAREST), &monitor))
      return;
    const RECT screen = monitor.rcMonitor;
    // A legacy fullscreen flag can accompany a small saved resolution. Keep
    // that mode resizable; a borderless window only makes sense at monitor size.
    const bool fullscreen = !mode.windowed &&
        mode.width == screen.right - screen.left &&
        mode.height == screen.bottom - screen.top;
    const DWORD style = fullscreen ? WS_POPUP : WS_OVERLAPPEDWINDOW;
    const auto previous = GetWindowLongPtrW(hwnd_, GWL_STYLE);
    const bool style_changed = (previous & (WS_OVERLAPPEDWINDOW | WS_POPUP)) != style;
    RECT client{};
    GetClientRect(hwnd_, &client);
    if (style_changed || client.right != mode.width || client.bottom != mode.height) {
      if (IsZoomed(hwnd_)) ShowWindow(hwnd_, SW_RESTORE);
      SetWindowLongPtrW(hwnd_, GWL_STYLE,
          (previous & ~(WS_OVERLAPPEDWINDOW | WS_POPUP)) | style);
      RECT frame{0, 0, mode.width, mode.height};
      AdjustWindowRectEx(&frame, style, FALSE, GetWindowLongW(hwnd_, GWL_EXSTYLE));
      const RECT area = fullscreen ? screen : monitor.rcWork;
      const int w = frame.right - frame.left, h = frame.bottom - frame.top;
      const int x = area.left + std::max(0, int(area.right - area.left - w) / 2);
      const int y = area.top + std::max(0, int(area.bottom - area.top - h) / 2);
      SetWindowPos(hwnd_, nullptr, x, y, w, h,
                   SWP_NOZORDER | SWP_NOACTIVATE | SWP_FRAMECHANGED);
    }
  }
#endif
  applied_video_mode_ = mode;
}

  bool LibBgfxBackend::ensure_scene_target(uint16_t width, uint16_t height) {
    if (!bgfx::isValid(present_program_) || width == 0 || height == 0) return false;
    uint64_t msaa = 0;
    const uint32_t mask = reset_flags_ & BGFX_RESET_MSAA_MASK;
    if (mask == BGFX_RESET_MSAA_X8) msaa = BGFX_TEXTURE_RT_MSAA_X8;
    else if (mask == BGFX_RESET_MSAA_X4) msaa = BGFX_TEXTURE_RT_MSAA_X4;
    else if (mask == BGFX_RESET_MSAA_X2) msaa = BGFX_TEXTURE_RT_MSAA_X2;
    if (bgfx::isValid(scene_fb_) && scene_w_ == width && scene_h_ == height &&
        scene_msaa_ == msaa)
      return true;
    destroy_scene_target();
    const uint64_t sample = BGFX_SAMPLER_U_CLAMP | BGFX_SAMPLER_V_CLAMP |
                            BGFX_SAMPLER_MIN_POINT | BGFX_SAMPLER_MAG_POINT;
    if (msaa != 0) {
      const uint64_t rt = BGFX_TEXTURE_RT | msaa | sample;
      bgfx::TextureHandle attachments[2] = {
          bgfx::createTexture2D(width, height, false, 1, bgfx::TextureFormat::RGBA8, rt),
          bgfx::createTexture2D(width, height, false, 1, bgfx::TextureFormat::D32F, rt)};
      if (!bgfx::isValid(attachments[0]) || !bgfx::isValid(attachments[1])) {
        if (bgfx::isValid(attachments[0])) bgfx::destroy(attachments[0]);
        if (bgfx::isValid(attachments[1])) bgfx::destroy(attachments[1]);
        return false;
      }
      scene_fb_ = bgfx::createFrameBuffer(2, attachments, true);
      const uint64_t resolve = BGFX_TEXTURE_BLIT_DST | sample;
      scene_color_ = bgfx::createTexture2D(width, height, false, 1,
                                           bgfx::TextureFormat::RGBA8, resolve);
      scene_depth_ = bgfx::createTexture2D(width, height, false, 1,
                                           bgfx::TextureFormat::D32F, resolve);
    } else {
      const uint64_t rt = BGFX_TEXTURE_RT | sample;
      scene_color_ = bgfx::createTexture2D(width, height, false, 1,
                                           bgfx::TextureFormat::RGBA8, rt);
      scene_depth_ = bgfx::createTexture2D(width, height, false, 1,
                                           bgfx::TextureFormat::D32F, rt);
      if (!bgfx::isValid(scene_color_) || !bgfx::isValid(scene_depth_)) {
        destroy_scene_target();
        return false;
      }
      const bgfx::TextureHandle attachments[] = {scene_color_, scene_depth_};
      scene_fb_ = bgfx::createFrameBuffer(2, attachments, false);
    }
    if (!bgfx::isValid(scene_fb_) || !bgfx::isValid(scene_color_) ||
        !bgfx::isValid(scene_depth_)) {
      destroy_scene_target();
      return false;
    }
    scene_w_ = width;
    scene_h_ = height;
    scene_msaa_ = msaa;
    return true;
  }

  void LibBgfxBackend::destroy_scene_target() {
    if (bgfx::isValid(scene_fb_)) bgfx::destroy(scene_fb_);
    scene_fb_ = BGFX_INVALID_HANDLE;
    if (bgfx::isValid(scene_color_)) bgfx::destroy(scene_color_);
    if (bgfx::isValid(scene_depth_)) bgfx::destroy(scene_depth_);
    scene_color_ = BGFX_INVALID_HANDLE;
    scene_depth_ = BGFX_INVALID_HANDLE;
    scene_w_ = 0;
    scene_h_ = 0;
    scene_msaa_ = 0;
  }


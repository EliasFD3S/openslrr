  void LibBgfxBackend::flip_logo_uv_horizontal(ScxGeometry& geo)
{
    if (geo.uvs.empty() || geo.groups.empty()) return;
    std::vector<char> mark(geo.uvs.size() / 2, 0);
    for (const ScxGroup& g : geo.groups) {
      if (!is_logo_group(g, geo)) continue;
      const uint32_t end = g.index_start + g.index_count;
      for (uint32_t i = g.index_start; i < end && i < geo.indices.size(); ++i) {
        const uint32_t vi = geo.indices[i];
        if (vi < mark.size()) mark[vi] = 1;
      }
    }
    int flipped = 0;
    for (size_t i = 0; i < mark.size(); ++i) {
      if (!mark[i]) continue;
      geo.uvs[i * 2 + 0] = 1.f - geo.uvs[i * 2 + 0];
      ++flipped;
    }
    if (flipped)
      std::printf("[bgfx] logo UV horizontal flip verts=%d\n", flipped);
  }
  void LibBgfxBackend::draw_scene(uint16_t view_id)
{
    float mtx[16];
    bx::mtxIdentity(mtx);
    // Stock map faces are two-sided. Culling either winding hid a side of
    // the shell (interior or the floor underside).
    const uint64_t state_opaque = BGFX_STATE_WRITE_RGB | BGFX_STATE_WRITE_A |
                                  BGFX_STATE_WRITE_Z |
                                  BGFX_STATE_DEPTH_TEST_LESS | BGFX_STATE_MSAA;
    // Alpha cutout: no cull (fences / window cards / foliage two-sided).
    const uint64_t state_cutout = BGFX_STATE_WRITE_RGB | BGFX_STATE_WRITE_A |
                                  BGFX_STATE_WRITE_Z |
                                  BGFX_STATE_DEPTH_TEST_LESS | BGFX_STATE_MSAA;

    for (const ScenePart& part : parts_) {
      if (!bgfx::isValid(part.vbh) || !bgfx::isValid(part.ibh)) continue;
      auto submit_range = [&](uint32_t start, uint32_t count,
                              bgfx::TextureHandle tex, bool alpha_cutout,
                              const ScxGroup* group) {
        const float u[4] = {alpha_cutout ? 1.f : 0.f, 0.f, 0.f, 0.f};
        bgfx::setUniform(u_alpha_test_, u);
        const float white_c[4] = {1.f, 1.f, 1.f, 1.f};
        bgfx::setUniform(u_color_, white_c);
        bgfx::setTransform(mtx);
        bgfx::setVertexBuffer(0, part.vbh);
        bgfx::setIndexBuffer(part.ibh, start, count);
        bgfx::setTexture(0, s_tex_,
                         bgfx::isValid(tex) ? tex : white_tex_);
        bind_baked_light(group, &part.tex);
        bgfx::setState(alpha_cutout ? state_cutout : state_opaque);
        bgfx::submit(view_id, program_);
      };
      // v4: always honour DDS alpha (SLRR_rev scxDiffuseUsesAlpha).
      // v3: only when material flag alphaOpacity (0x1).
      auto group_cutout = [&](const ScxGroup& g) {
        if (part.geo.info.version != 3) return true;
        return (g.material_flags & 0x1u) != 0;
      };
      if (!part.geo.groups.empty()) {
        for (const ScxGroup& g : part.geo.groups) {
          bgfx::TextureHandle tex = BGFX_INVALID_HANDLE;
          if (g.texture_index != 0xffff && g.texture_index < part.tex.size())
            tex = part.tex[g.texture_index];
          else if (!part.tex.empty())
            tex = part.tex[0];
          submit_range(g.index_start, g.index_count, tex, group_cutout(g), &g);
        }
      } else {
        bgfx::TextureHandle tex = BGFX_INVALID_HANDLE;
        if (!part.tex.empty()) tex = part.tex[0];
        const bool cut =
            part.geo.info.version != 3;  // no groups: v4 yes, v3 opaque
        submit_range(0, static_cast<uint32_t>(part.geo.indices.size()), tex,
                     cut, nullptr);
      }
    }
  }
  void LibBgfxBackend::load_part_textures(ScenePart& part)
{
    std::vector<std::string> paths = part.geo.textures;
    if (paths.empty() && !part.geo.info.path.empty()) {
      std::string dir = part.geo.info.path;
      for (char& c : dir)
        if (c == '/') c = '\\';
      const auto slash = dir.find_last_of('\\');
      if (slash != std::string::npos) dir.resize(slash + 1);
#ifdef _WIN32
      WIN32_FIND_DATAA fd{};
      HANDLE h = FindFirstFileA((dir + "*.dds").c_str(), &fd);
      if (h != INVALID_HANDLE_VALUE) {
        do {
          if (!(fd.dwFileAttributes & FILE_ATTRIBUTE_DIRECTORY))
            paths.push_back(dir + fd.cFileName);
        } while (FindNextFileA(h, &fd));
        FindClose(h);
      }
#endif
      std::sort(paths.begin(), paths.end());
    }

    part.tex.assign(paths.size(), BGFX_INVALID_HANDLE);
    int loaded = 0;
    for (size_t i = 0; i < paths.size(); ++i) {
      std::string path = paths[i];
      for (char& c : path)
        if (c == '/') c = '\\';
      if (path.size() > 1 && path[1] != ':') {
        std::string base = part.geo.info.path;
        for (char& c : base)
          if (c == '/') c = '\\';
        const auto gpos = base.find("\\game\\");
        if (gpos != std::string::npos)
          path = base.substr(0, gpos + 6) + path;
        else {
          const auto misc = base.find("\\misc\\");
          if (misc != std::string::npos)
            path = base.substr(0, misc + 1) + path;
        }
      }
      // Paintable body slots (g1Auto.dds etc.) are solid lime placeholders;
      // stock replaces them with the paint color — default white.
      auto is_paint_stub = [](const std::string& p, const DdsImage& img) {
        std::string low = p;
        for (char& c : low)
          c = static_cast<char>(std::tolower(static_cast<unsigned char>(c)));
        if (low.find("auto.dds") != std::string::npos) return true;
        if (!img.ok || img.format != DdsFormat::DXT1 || img.data.size() < 8)
          return false;
        const uint8_t* b = img.data.data();
        const uint16_t c0 =
            static_cast<uint16_t>(b[0] | (static_cast<uint16_t>(b[1]) << 8));
        const int r = ((c0 >> 11) & 31) * 255 / 31;
        const int g = ((c0 >> 5) & 63) * 255 / 63;
        const int bl = (c0 & 31) * 255 / 31;
        return g > 140 && r > 100 && bl < 40 && g >= r;
      };

      DdsImage img = load_texture_file(path);
      if (!img.ok) {
        std::printf("[bgfx] DDS miss slot %zu %s\n", i, path.c_str());
        continue;
      }
      std::printf("[bgfx] DDS slot %zu %s %ux%u\n", i, path.c_str(), img.width,
                  img.height);
      if (is_paint_stub(path, img)) {
        part.tex[i] = white_tex_;
        ++loaded;
        std::printf("[bgfx] DDS slot %zu paint stub → white\n", i);
        continue;
      }
      bgfx::TextureFormat::Enum fmt = bgfx::TextureFormat::Unknown;
      if (img.format == DdsFormat::DXT1) fmt = bgfx::TextureFormat::BC1;
      else if (img.format == DdsFormat::DXT3) fmt = bgfx::TextureFormat::BC2;
      else if (img.format == DdsFormat::DXT5) fmt = bgfx::TextureFormat::BC3;
      else if (img.format == DdsFormat::RGBA8) {
        std::string ext=path.size()>=4?path.substr(path.size()-4):"";
        for(char& c:ext)c=static_cast<char>(std::tolower(static_cast<unsigned char>(c)));
        fmt=ext==".dds"?bgfx::TextureFormat::BGRA8:bgfx::TextureFormat::RGBA8;
      }
      else
        continue;
      const bgfx::Memory* mem =
          bgfx::copy(img.data.data(), img.mip0_size);
      // Wrap, same as the stock sampler. Mirror flips a tread that tiles
      // past 1 (the tyre runs U 0..4) so the grooves reverse every repeat.
      part.tex[i] = bgfx::createTexture2D(
          static_cast<uint16_t>(img.width), static_cast<uint16_t>(img.height),
          false, 1, fmt, 0, mem);
      if (bgfx::isValid(part.tex[i])) ++loaded;
    }
    std::printf("[bgfx] DDS GPU uploaded %d / %zu\n", loaded, paths.size());
  }

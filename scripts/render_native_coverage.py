#!/usr/bin/env python3
"""Regenerate the README native-binding coverage chart from the source tree.

The stock native table is pinned in assets/progress/stock-natives.json. The
host side is read statically from the register_method calls under src/, so a
newly bound native moves from "missing" to "with a body" without editing any
counts by hand. One run rewrites:

  assets/progress/native-coverage.json   counts per family
  assets/progress/native-coverage.svg    the chart shown in README.md
  README.md                              the summary line and table between
                                         the native-coverage markers

Usage:
  python scripts/render_native_coverage.py            regenerate the outputs
  python scripts/render_native_coverage.py --check    exit 1 if they are stale
  python scripts/render_native_coverage.py --list missing|noop|body
                                                      print matching signatures
  python scripts/render_native_coverage.py --import-stock natives_stubs.cpp
                                                      rebuild the stock table

Standard library only. No game data or build is needed.
"""


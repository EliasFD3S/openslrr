# ---------------------------------------------------------------------------
# Families. The first matching rule wins, so Leftovers and World precede the
# broader package rules they would otherwise fall into.

LEFTOVERS = {
    ("java.lang.System", "netHost"), ("java.lang.System", "netJoin"),
    ("java.lang.System", "netLeave"),
    # Welder is listed under RenderRef in the stock table.
    ("java.util.resource.RenderRef", "addPoints"),
    ("java.util.resource.RenderRef", "weld"),
    ("java.util.resource.RenderRef", "progress"),
}
WORLD = {"GroundRef", "PhysicsRef", "Animation", "ParticleSystem"}

FAMILIES = (
    ("World", lambda c, m: c.rsplit(".", 1)[-1] in WORLD),
    ("Language", lambda c, m: (c, m) not in LEFTOVERS and c.startswith("java.lang.")),
    ("Sound & scripts", lambda c, m: c.startswith("java.sound.") or
        (c.startswith("java.game.") and not c.startswith("java.game.parts."))),
    ("Resources", lambda c, m: (c, m) not in LEFTOVERS and c.startswith("java.util.resource.")),
    ("Rendering", lambda c, m: c.startswith("java.render.")),
    ("Files & input", lambda c, m: c.startswith("java.io.")),
    ("Parts", lambda c, m: c.startswith("java.game.parts.")),
    ("Leftovers", lambda c, m: (c, m) in LEFTOVERS),
)


def family_of(class_name: str, method: str) -> str:
    for name, matches in FAMILIES:
        if matches(class_name, method):
            return name
    raise SystemExit(f"native coverage: no family for stock native {class_name}.{method}")


# ---------------------------------------------------------------------------
# Stock table

PRIMITIVES = {"void": "V", "int": "I", "float": "F"}
SPECIAL_TYPES = {
    "String": "java.lang.String", "Object": "java.lang.Object",
    "Vector3": "java.lang.Vector3", "Ypr": "java.lang.Ypr",
    "GameType": "java.lang.GameType", "Hotkey": "java.io.Hotkey",
    "Osd": "java.render.Osd",
}


def descriptor_type(java_type: str, owners: dict[str, str]) -> str:
    java_type = re.sub(r"\s+", "", java_type)
    if java_type.endswith("[]"):
        return "[" + descriptor_type(java_type[:-2], owners)
    if java_type in PRIMITIVES:
        return PRIMITIVES[java_type]
    owner = SPECIAL_TYPES.get(java_type) or owners.get(java_type)
    if not owner:
        raise SystemExit(f"native coverage: unmapped stock type {java_type}")
    return f"L{owner};"


def stock_descriptor(typed_signature: str, owners: dict[str, str]) -> str:
    match = re.fullmatch(r"(.+?)\s+[^ (]+\((.*)\)", typed_signature)
    if not match:
        raise SystemExit(f"native coverage: invalid stock signature {typed_signature}")
    args = match.group(2).strip()
    types = ["".join(arg.split()[:-1]) for arg in args.split(",")] if args else []
    return "(" + "".join(descriptor_type(t, owners) for t in types) + ")"


def import_stock(path: Path) -> None:
    data = path.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != STOCK_SHA256:
        raise SystemExit(f"native coverage: {path} has SHA-256 {digest}, expected {STOCK_SHA256}")
    rows = [
        {"class": c, "method": m, "typed_signature": s}
        for c, m, s in re.findall(r'\{"([^"]+)",\s*"([^"]+)",\s*"([^"]+)",\s*(?:true|false),',
                                  data.decode("utf-8"))
    ]
    owners = {row["class"].rsplit(".", 1)[-1]: row["class"] for row in rows}
    for row in rows:
        row["descriptor"] = stock_descriptor(row["typed_signature"], owners)
    document = load_stock_document()
    document.update(count=len(rows), signatures=rows)
    validate_stock(document)
    write_text(STOCK_PATH, json_text(document))
    print(f"Wrote {STOCK_PATH.relative_to(ROOT).as_posix()} ({len(rows)} stock signatures)")


def load_stock_document() -> dict:
    return json.loads(STOCK_PATH.read_text(encoding="utf-8"))


def validate_stock(document: dict) -> list[dict]:
    rows = document.get("signatures") or []
    if document.get("source", {}).get("sha256") != STOCK_SHA256:
        raise SystemExit("native coverage: stock table does not name the pinned source")
    if document.get("count") != STOCK_COUNT or len(rows) != STOCK_COUNT:
        raise SystemExit(f"native coverage: stock table must hold {STOCK_COUNT} signatures")
    owners = {row["class"].rsplit(".", 1)[-1]: row["class"] for row in rows}
    seen = set()
    for row in rows:
        identity = (row["class"], row["method"], row["descriptor"])
        if identity in seen:
            raise SystemExit(f"native coverage: duplicate stock signature {identity}")
        seen.add(identity)
        if stock_descriptor(row["typed_signature"], owners) != row["descriptor"]:
            raise SystemExit(f"native coverage: stock descriptor mismatch for {identity}")
    return rows



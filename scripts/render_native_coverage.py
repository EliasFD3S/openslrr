# Host registrations: a small evaluator for the register_method call forms the
# sources use (literals, named constants, range-for loops over literal lists,
# ternaries, and local helper lambdas that forward to register_method).

STRING_RE = r'"(?:\\.|[^"\\])*"'


def strip_comments(text: str) -> str:
    out = list(text)
    i, state = 0, "code"
    while i < len(text):
        ch, nxt = text[i], text[i + 1] if i + 1 < len(text) else ""
        if state == "code":
            if ch in "\"'":
                state = ch
            elif ch == "/" and nxt == "/":
                out[i] = out[i + 1] = " "
                i += 1
                state = "line"
            elif ch == "/" and nxt == "*":
                out[i] = out[i + 1] = " "
                i += 1
                state = "block"
        elif state in "\"'":
            if ch == "\\":
                i += 1
            elif ch == state:
                state = "code"
        elif state == "line":
            if ch == "\n":
                state = "code"
            else:
                out[i] = " "
        elif state == "block":
            if ch == "*" and nxt == "/":
                out[i] = out[i + 1] = " "
                i += 1
                state = "code"
            elif ch != "\n":
                out[i] = " "
        i += 1
    return "".join(out)


def matching(text: str, start: int) -> int:
    """Index of the bracket closing the one at text[start]."""
    pairs = {"(": ")", "[": "]", "{": "}"}
    stack, state, i = [], "code", start
    while i < len(text):
        ch = text[i]
        if state != "code":
            if ch == "\\":
                i += 1
            elif ch == state:
                state = "code"
        elif ch in "\"'":
            state = ch
        elif ch in pairs:
            stack.append(pairs[ch])
        elif ch in ")]}":
            if not stack or stack.pop() != ch:
                break
            if not stack:
                return i
        i += 1
    raise ValueError(f"unbalanced bracket at offset {start}")


def split_top_level(text: str, delimiter: str = ",") -> list[str]:
    parts, depth, state, start, i = [], 0, "code", 0, 0
    while i < len(text):
        ch = text[i]
        if state != "code":
            if ch == "\\":
                i += 1
            elif ch == state:
                state = "code"
        elif ch in "\"'":
            state = ch
        elif ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        elif ch == delimiter and depth == 0:
            parts.append(text[start:i].strip())
            start = i + 1
        i += 1
    parts.append(text[start:].strip())
    return parts


def find_top_level(text: str, sought: str, start: int = 0) -> int:
    depth, state, i = 0, "code", start
    while i < len(text):
        ch = text[i]
        if state != "code":
            if ch == "\\":
                i += 1
            elif ch == state:
                state = "code"
        elif ch in "\"'":
            state = ch
        elif ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        elif depth == 0 and ch == sought:
            return i
        i += 1
    return -1


def call_arguments(text: str, name_end: int) -> tuple[list[str], int]:
    open_paren = text.index("(", name_end)
    close = matching(text, open_paren)
    return split_top_level(text[open_paren + 1:close]), close


def evaluate(expr: str, env: dict, constants: dict):
    expr = expr.strip()
    while expr.startswith("(") and matching(expr, 0) == len(expr) - 1:
        expr = expr[1:-1].strip()
    question = find_top_level(expr, "?")
    if question >= 0:
        colon = find_top_level(expr, ":", question + 1)
        while colon >= 0 and expr[colon + 1:colon + 2] == ":":
            colon = find_top_level(expr, ":", colon + 2)
        if colon < 0:
            raise ValueError(f"unterminated conditional: {expr}")
        condition = expr[:question].strip()
        comparison = re.fullmatch(r"(\w+)\s*(==|!=|>|<)\s*(-?\d+)", condition)
        if comparison:
            left, op, right = env.get(comparison.group(1)), comparison.group(2), int(comparison.group(3))
            if not isinstance(left, int) or isinstance(left, bool):
                raise ValueError(f"unsupported condition: {condition}")
            selected = {"==": left == right, "!=": left != right,
                        ">": left > right, "<": left < right}[op]
        elif isinstance(env.get(condition.lstrip("!")), bool):
            selected = env[condition.lstrip("!")] != condition.startswith("!")
        else:
            raise ValueError(f"unsupported condition: {condition}")
        return evaluate(expr[question + 1:colon] if selected else expr[colon + 1:], env, constants)
    pieces = split_top_level(expr, "+")
    if len(pieces) > 1:
        return "".join(str(evaluate(piece, env, constants)) for piece in pieces)
    if expr.startswith('"'):
        literals = re.findall(STRING_RE, expr)
        if re.sub(STRING_RE, "", expr).strip():
            raise ValueError(f"unsupported string expression: {expr}")
        return "".join(json.loads(literal) for literal in literals)
    if expr in env:
        return env[expr]
    if expr in constants:
        return constants[expr]
    raise ValueError(f"cannot resolve {expr!r}")


def literal_value(token: str):
    token = token.strip()
    if re.fullmatch(STRING_RE, token):
        return json.loads(token)
    if token in ("true", "false"):
        return token == "true"
    if re.fullmatch(r"-?\d+", token):
        return int(token)
    raise ValueError(token)


def loop_bindings(variable: str, element: str) -> dict:
    """Bindings for one element: a literal, or a braced pair/tuple of them."""
    element = element.strip()
    if not element.startswith("{"):
        return {variable: literal_value(element)}
    bindings = {}
    for field, item in zip(("first", "second"), split_top_level(element[1:-1])):
        try:
            bindings[f"{variable}.{field}"] = literal_value(item)
        except ValueError:
            pass  # e.g. a member pointer; registrations never name it
    if not bindings:
        raise ValueError(element)
    return bindings


def range_loops(text: str) -> list[tuple[int, int, list[dict]]]:
    """for (T name : {element, ...}) bodies, as (start, end, bindings)."""
    loops = []
    for match in re.finditer(r"\bfor\s*\(", text):
        open_paren = text.index("(", match.start())
        close = matching(text, open_paren)
        header = text[open_paren + 1:close]
        colon = next((i for i, ch in enumerate(header)
                      if ch == ":" and header[i - 1:i] != ":" and header[i + 1:i + 2] != ":"), -1)
        if colon < 0:
            continue
        variable = re.search(r"(\w+)\s*$", header[:colon])
        range_text = header[colon + 1:].strip()
        brace = range_text.find("{")
        # A braced list, optionally typed: {..} or std::vector<...>{..}.
        if not variable or brace < 0 or not range_text.endswith("}") or \
                matching(range_text, brace) != len(range_text) - 1 or \
                not re.fullmatch(r"[\w:<>,*&\s]*", range_text[:brace]):
            continue
        try:
            values = [loop_bindings(variable.group(1), element)
                      for element in split_top_level(range_text[brace + 1:-1])]
        except ValueError:
            continue
        body = close + 1
        while body < len(text) and text[body].isspace():
            body += 1
        end = matching(text, body) if text[body] == "{" else text.index(";", body)
        loops.append((body, end, values))
    return loops


def environments(loops, offset: int):
    active = [values for start, end, values in loops if start <= offset <= end]
    for combination in itertools.product(*active):
        env = {}
        for bindings in combination:
            env.update(bindings)
        yield env


def string_constants(text: str) -> dict[str, str]:
    pattern = (r"\b(?:constexpr\s+|static\s+|inline\s+|const\s+)*"
               r"(?:char|auto|std::string(?:_view)?)\s*(?:const\s*)?\*?\s*(?:const\s+)?"
               r"(\w+)\s*(?:\[\s*\])?\s*=\s*(" + STRING_RE + r")\s*;")
    return {name: json.loads(value) for name, value in re.findall(pattern, text)}


def helper_lambdas(text: str) -> dict[str, tuple[list[str], list[str], int, int]]:
    """auto name = [...](params) { ... register_method(args) ... };"""
    helpers = {}
    for match in re.finditer(r"\bauto\s+(\w+)\s*=\s*\[", text):
        capture = text.index("[", match.start())
        params_open = capture_end = matching(text, capture) + 1
        while params_open < len(text) and text[params_open].isspace():
            params_open += 1
        if text[params_open:params_open + 1] != "(":
            continue
        params_close = matching(text, params_open)
        body_open = text.find("{", params_close)
        if body_open < 0 or text[params_close + 1:body_open].strip() not in ("", "mutable"):
            continue
        body_close = matching(text, body_open)
        body = text[body_open:body_close]
        calls = list(re.finditer(r"\bregister_method\s*\(", body))
        if len(calls) != 1:
            continue
        args, _ = call_arguments(body, calls[0].end() - 1)
        params = [re.search(r"(\w+)\s*$", p).group(1)
                  for p in split_top_level(text[params_open + 1:params_close]) if p]
        helpers[match.group(1)] = (params, args, capture_end, body_close)
    return helpers


def descriptor_parameters(descriptor: str) -> str:
    descriptor = descriptor.replace("/", ".")
    close = descriptor.find(")")
    if not descriptor.startswith("(") or close < 0:
        raise ValueError(f"invalid descriptor {descriptor}")
    return descriptor[:close + 1]


def host_registrations() -> dict[tuple[str, str, str], str]:
    found: dict[tuple[str, str, str], str] = {}
    for path in sorted(SOURCE_DIR.rglob("*.cpp")):
        relative = path.relative_to(ROOT).as_posix()
        if relative in SKIPPED_SOURCES:
            continue
        text = strip_comments(path.read_text(encoding="utf-8", errors="replace"))
        if "register_method" not in text:
            continue
        constants, loops, helpers = string_constants(text), range_loops(text), helper_lambdas(text)
        inside_helper = [(start, end) for _, _, start, end in helpers.values()]
        sites = []  # (offset, [class, method, descriptor, handler...], parameter env)
        for match in re.finditer(r"\bregister_method\s*\(", text):
            if any(start <= match.start() <= end for start, end in inside_helper):
                continue
            args, _ = call_arguments(text, match.end() - 1)
            sites.append((match.start(), args, {}))
        for name, (params, forwarded, start, end) in helpers.items():
            for match in re.finditer(rf"(?<![\w.>:]){re.escape(name)}\s*\(", text):
                if start <= match.start() <= end or text[:match.start()].rstrip().endswith("auto"):
                    continue
                args, _ = call_arguments(text, match.end() - 1)
                if len(args) != len(params):
                    continue
                sites.append((match.start(), forwarded, dict(zip(params, args))))
        for offset, args, params in sites:
            line = text.count("\n", 0, offset) + 1
            if len(args) < 4:
                raise SystemExit(f"native coverage: {relative}:{line}: incomplete register_method call")
            for env in environments(loops, offset):
                try:
                    resolved = [
                        evaluate(params.get(arg.strip(), arg), env, constants) for arg in args[:3]
                    ]
                    key = (resolved[0], resolved[1], descriptor_parameters(resolved[2]))
                except (ValueError, TypeError) as error:
                    raise SystemExit(
                        f"native coverage: {relative}:{line}: {error}; extend "
                        "scripts/render_native_coverage.py or use a literal registration")
                rest = [arg.strip() for arg in args[3:]]
                # An optional trailing NativeImplementation tag is not the handler.
                tagged_noop = False
                if len(rest) > 1 and rest[-1].startswith("NativeImplementation::"):
                    tagged_noop = rest.pop() == "NativeImplementation::ExplicitNoop"
                handler = ",".join(rest).strip()
                moved = re.fullmatch(r"std::move\((\w+)\)", handler)
                handler = params.get(moved.group(1) if moved else handler, handler).strip()
                kind = "noop" if tagged_noop or handler == "native_noop" else "body"
                if found.get(key, kind) != kind:
                    raise SystemExit(f"native coverage: conflicting registrations for {key}")
                found[key] = kind
    return found


# ---------------------------------------------------------------------------
# Coverage model

def classify() -> list[tuple[dict, str, str]]:
    rows = validate_stock(load_stock_document())
    host = host_registrations()
    result = []
    for row in rows:
        key = (row["class"], row["method"], descriptor_parameters(row["descriptor"]))
        result.append((row, family_of(row["class"], row["method"]), host.get(key, "missing")))
    return result


def coverage(updated: str) -> dict:
    counts = {name: dict.fromkeys(KINDS, 0) for name, _ in FAMILIES}
    for _, family, kind in classify():
        counts[family][kind] += 1
    categories = [{"name": name, **counts[name]} for name, _ in FAMILIES]
    return {
        "updated": updated,
        "total": sum(sum(row[k] for k in KINDS) for row in categories),
        "scope": (
            "Stock native table (assets/progress/stock-natives.json), matched against the "
            "class/method/parameter signatures registered under src/ by "
            "scripts/render_native_coverage.py. Explicit native_noop bindings are counted "
            "separately. Bodies can be partial implementations or return constants; these "
            "are binding counts, not gameplay-completion or validation scores."
        ),
        "categories": categories,
    }


def counts_of(document: dict | None):
    if not document:
        return None
    return [(row["name"], *(row[k] for k in KINDS)) for row in document.get("categories", [])]



COLORS = {"body": "#49a58d", "noop": "#d39338", "missing": "#ab474b"}
LABELS = {"body": "with a body", "noop": "no-op", "missing": "missing"}
CHART_LEFT, CHART_WIDTH = 170, 870
ROW_TOP, ROW_STEP, BAR_HEIGHT = 85, 35, 25
INNER_LABEL_MIN_WIDTH = 30


def number(value: float) -> str:
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return "0" if text == "-0" else text


def escape(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def totals(document: dict) -> dict[str, int]:
    return {k: sum(row[k] for row in document["categories"]) for k in KINDS}


def svg_text(document: dict) -> str:
    total, sums = document["total"], totals(document)
    rows = document["categories"]
    largest = max(sum(row[k] for k in KINDS) for row in rows)
    axis_max = max(100, math.ceil(largest / 100) * 100)
    scale = CHART_WIDTH / axis_max
    bottom = ROW_TOP + len(rows) * ROW_STEP
    height = bottom + 100
    summary = f"{sums['body']} with a body  /  {sums['noop']} no-op  /  {sums['missing']} missing"
    lines = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="1120" height="{height}" '
        f'viewBox="0 0 1120 {height}" role="img" aria-labelledby="title desc">',
        '<title id="title">Open SLRR native binding coverage</title>',
        f'<desc id="desc">{sums["body"]} with a body, {sums["noop"]} no-op, {sums["missing"]} '
        f'missing, out of {total}. Bars show counts, not percentages of game completion.</desc>',
        f'<rect width="1120" height="{height}" rx="12" fill="#0d1117"/>',
        '<g font-family="Segoe UI,Arial,sans-serif">',
        '<text x="28" y="34" font-size="21" fill="#f0f6fc" text-anchor="start">Native binding coverage</text>',
        f'<text x="28" y="58" font-size="13" fill="#c9d1d9" text-anchor="start">{summary}  ·  '
        f'{total} stock natives</text>',
    ]
    for tick in range(5):
        x = number(CHART_LEFT + tick * CHART_WIDTH / 4)
        lines.append(f'<line x1="{x}" x2="{x}" y1="80" y2="{bottom - 4}" stroke="#21262d"/>')
        lines.append(f'<text x="{x}" y="{bottom + 16}" font-size="12" fill="#8b949e" '
                     f'text-anchor="middle">{number(tick * axis_max / 4)}</text>')
    for index, row in enumerate(rows):
        y, name = ROW_TOP + index * ROW_STEP, escape(row["name"])
        lines.append(f'<text x="156" y="{y + 17}" font-size="13" fill="#c9d1d9" '
                     f'text-anchor="end">{name}</text>')
        x = float(CHART_LEFT)
        for kind in KINDS:
            count = row[kind]
            if not count:
                continue
            width = count * scale
            lines.append(f'<rect x="{number(x)}" y="{y}" width="{number(width)}" '
                         f'height="{BAR_HEIGHT}" fill="{COLORS[kind]}"><title>{name}: {count} '
                         f'{LABELS[kind]}</title></rect>')
            if width >= INNER_LABEL_MIN_WIDTH:
                lines.append(f'<text x="{number(x + width / 2)}" y="{y + 17}" font-size="12" '
                             f'fill="#ffffff" text-anchor="middle">{count}</text>')
            x += width
        lines.append(f'<text x="{number(x + 10)}" y="{y + 17}" font-size="12" fill="#8b949e" '
                     f'text-anchor="start">{sum(row[k] for k in KINDS)}</text>')
    lines += [
        f'<text x="{CHART_LEFT + CHART_WIDTH}" y="{bottom + 39}" font-size="12" fill="#8b949e" '
        'text-anchor="end">Number of natives</text>',
    ]
    for kind, x in (("body", 170), ("noop", 360), ("missing", 493)):
        lines.append(f'<rect x="{x}" y="{bottom + 50}" width="12" height="12" rx="2" '
                     f'fill="{COLORS[kind]}"/>')
        lines.append(f'<text x="{x + 20}" y="{bottom + 61}" font-size="13" fill="#c9d1d9" '
                     f'text-anchor="start">{LABELS[kind].capitalize()}</text>')
    lines += [
        f'<text x="1090" y="{bottom + 81}" font-size="11" fill="#8b949e" text-anchor="end">'
        f'Audited {document["updated"]} · Bodies may be partial implementations</text>',
        "</g>",
        "</svg>",
    ]
    return "\n".join(lines) + "\n"


MONTHS = ("January", "February", "March", "April", "May", "June", "July",
          "August", "September", "October", "November", "December")


def plural(count: int, singular: str, many: str) -> str:
    return f"{count} {singular if count == 1 else many}"


def readme_block(document: dict) -> str:
    sums = totals(document)
    date = dt.date.fromisoformat(document["updated"])
    lines = [
        README_START,
        f"**{sums['body']} with a body · {plural(sums['noop'], 'explicit no-op', 'explicit no-ops')}"
        f" · {sums['missing']} missing**, out of **{document['total']} stock natives** "
        f"({date.day} {MONTHS[date.month - 1]} {date.year}).",
        "The bars show **numbers of functions**, not percentages. A body can still be partial or "
        "return a fixed value; these counts do not establish full behavior or validation in game. "
        "The separately counted no-op functions are explicitly registered as `native_noop`.",
        "",
        "| Family | With a body | No-op | Missing |",
        "| --- | ---: | ---: | ---: |",
    ]
    for row in document["categories"]:
        lines.append(f"| {row['name']} | {row['body']} | {row['noop']} | {row['missing']} |")
    lines.append(f"| **Total** | **{sums['body']}** | **{sums['noop']}** | **{sums['missing']}** |")
    lines.append(README_END)
    return "\n".join(lines)


def readme_text(current: str, document: dict) -> str:
    start, end = current.find(README_START), current.find(README_END)
    if start < 0 or end < start:
        raise SystemExit("native coverage: README.md lacks the native-coverage markers")
    return current[:start] + readme_block(document) + current[end + len(README_END):]


def json_text(document: dict) -> str:
    return json.dumps(document, indent=2, ensure_ascii=False) + "\n"


def read_text(path: Path) -> str | None:
    # Git for Windows may check text out with CRLF; compare content, not newlines.
    if not path.exists():
        return None
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def write_text(path: Path, text: str) -> None:
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def expected_outputs(today: str) -> dict[Path, str]:
    previous_text = read_text(JSON_PATH)
    previous = json.loads(previous_text) if previous_text else None
    document = coverage(today)
    # Keep the audit date unless the counts changed, so reruns are stable.
    if previous and counts_of(previous) == counts_of(document) and previous.get("updated"):
        document["updated"] = previous["updated"]
    readme = read_text(README_PATH) or ""
    return {
        JSON_PATH: json_text(document),
        SVG_PATH: svg_text(document),
        README_PATH: readme_text(readme, document),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true", help="fail if the outputs are stale")
    group.add_argument("--list", choices=KINDS, help="print stock natives of one kind")
    group.add_argument("--import-stock", type=Path, metavar="FILE",
                       help="rebuild the stock table from slrr-reverse natives_stubs.cpp")
    parser.add_argument("--date", default=dt.date.today().isoformat(),
                        help="audit date to record when the counts change (YYYY-MM-DD)")
    args = parser.parse_args()
    dt.date.fromisoformat(args.date)

    if args.import_stock:
        import_stock(args.import_stock)
        return 0
    if args.list:
        for row, family, kind in classify():
            if kind == args.list:
                print(f"{family:16} {row['class']}.{row['method']}{row['descriptor']}")
        return 0
    outputs = expected_outputs(args.date)
    stale = [path for path, text in outputs.items() if read_text(path) != text]
    if args.check:
        for path in stale:
            print(f"STALE: {path.relative_to(ROOT).as_posix()}; "
                  "run python scripts/render_native_coverage.py")
        if not stale:
            print("Native coverage JSON, SVG and README table are up to date.")
        return 1 if stale else 0
    for path in stale:
        write_text(path, outputs[path])
        print(f"Wrote {path.relative_to(ROOT).as_posix()}")
    if not stale:
        print("Native coverage outputs already up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
